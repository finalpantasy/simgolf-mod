"""Generate fingerprint metadata from a clean disc extraction, never from a played install.

python tools/release/game_manifest.py <extracted game folder> <output header>
Only paths, lengths and SHA256 fingerprints are emitted; no game bytes.
"""
import hashlib
import json
from pathlib import Path
import sys


def generate(root, output):
    rows = []
    for path in sorted(root.rglob('*'), key=lambda p: p.as_posix().lower()):
        if not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        # Player state and programs are not imported. top10 is recreated by the game.
        if rel.lower() in ('golf.exe', 'golf_nocd.exe', 'top10.sve', 'logfile.txt'):
            continue
        if rel.split('/')[0].lower() in ('saved games', 'snapshots'):
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        rows.append('  {%s, %d, "%s"},' % (json.dumps(rel), path.stat().st_size, digest))
    output.write_text('// Original English disc data: paths, sizes and SHA256 only.\n'
                      '// Generated by tools/release/game_manifest.py from a clean disc extraction.\n'
                      'static const GameFile game_files[] = {\n' + '\n'.join(rows) + '\n};\n', encoding='utf-8')
    print('manifest: %d files' % len(rows))


if __name__ == '__main__':
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
